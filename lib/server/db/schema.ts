/**
 * One row per device (browser) that accepted notifications. The endpoint is the push
 * service's address for that browser, unique worldwide: if another account signs in on the
 * same browser and turns notifications on, the row moves to that account.
 */
export const pushSubscriptions = pgTable(
  'push_subscriptions',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    endpoint: text('endpoint').notNull().unique(),
    /** The browser's public key and auth secret, used to encrypt every payload. */
    p256dh: text('p256dh').notNull(),
    auth: text('auth').notNull(),
    /** To tell the devices apart in Settings ("Chrome no Android"). */
    userAgent: text('user_agent'),
    createdAt: createdAt(),
    /** Last time the push service accepted a notification for this device. */
    lastSuccessAt: timestamp('last_success_at', { withTimezone: true }),
  },
  (t) => [index('push_subscriptions_user_id_idx').on(t.userId)],
);

/**
 * One row per notification shown in the in-app bell — the full history of everything the app
 * has told this account, whether or not push itself reached a device. `sourceKey` is set only
 * for notifications a background job could generate again for the same reason (a feature
 * announcement, for instance); the unique index on (user, source key) keeps those from being
 * recorded twice, while ad-hoc notifications (reminders — sourceKey null) are
 * never deduped by it, since NULL never equals NULL in a Postgres unique index.
 *
 * `dismissedAt` is what makes that dedupe survive the swipe-to-dismiss gesture: throwing a
 * notification with a `sourceKey` away only hides the row, leaving it as a headstone the unique
 * index still sees, so the job that created it does not simply create it again on its next run.
 * One without a `sourceKey` is nobody's to recreate, so it is deleted outright.
 */
export const notifications = pgTable(
  'notifications',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    category: text('category').$type<NotificationCategory>().notNull(),
    title: text('title').notNull(),
    body: text('body').notNull(),
    href: text('href'),
    sourceKey: text('source_key'),
    readAt: timestamp('read_at', { withTimezone: true }),
    /** Set when the person swiped it away: the row stays, the bell stops showing it. */
    dismissedAt: timestamp('dismissed_at', { withTimezone: true }),
    createdAt: createdAt(),
  },
  (t) => [
    index('notifications_user_created_idx').on(t.userId, t.createdAt),
    unique('notifications_user_source_unique').on(t.userId, t.sourceKey),
  ],
);


